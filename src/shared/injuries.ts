export function findInjury(id: string): Injury | null {
	return INJURIES.find((injury) => injury.id === id) ?? null
}

/** Зоны, по которым в справочнике есть хоть одна травма, в порядке появления. */
export function injuryZones(injuries: readonly Injury[] = INJURIES): BodyZone[] {
	return [...new Set(injuries.map((injury) => injury.zone))]
}

export function injuriesInZone(zone: BodyZone | null, injuries: readonly Injury[] = INJURIES): Injury[] {
	return injuries.filter((injury) => !zone || injury.zone === zone)
}
