export type Injury = {
	/** Ключ в адресе и в стеке экранов. */
	id: string
	title: string
	/** Короткое название для списка и чипов: "ПКС", "мениск". */
	short: string
	zone: BodyZone
	summary: string
	/** Движения и ситуации в кроссфите, на которых травма случается чаще всего. */
	causes: string[]
	symptoms: string[]
	/** Признаки, с которыми к врачу идут сразу, не дожидаясь, что "само пройдёт". */
	redFlags: string[]
	firstSteps: string[]
	/** Чем заменить или как облегчить движения, пока зона восстанавливается. */
	modifications: { avoid: string; instead: string }[]
	image: { src: string; alt: string; caption: string } | null
}

